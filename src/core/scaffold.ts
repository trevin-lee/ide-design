function write(file: string, content: string, overwrite = false) {
  if (!overwrite && existsSync(file)) return false;
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
  return true;
}

export function pascal(slug: string): string {
  const s = slug.replace(/(^|-)([a-z0-9])/g, (_, __, c: string) => c.toUpperCase());
  return /^[0-9]/.test(s) ? `Frame${s}` : s;
}

export function titleCase(slug: string): string {
  return slug.replace(/-/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());
}

export function slugify(input: string): string {
  return input
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

