export interface NewProjectOptions {
  title?: string;
  paper?: "letter" | "a4";
  size?: string;
  /** One viewport, or several separated by commas ("desktop,mobile") for a responsive screen. */
  viewport?: string | readonly string[];
}

/** Options that only apply to some kinds, so one given to another kind is a mistake, not a no-op. */
const OPTION_KINDS = { paper: "doc", size: "graphic", viewport: "web" } as const;

export function manifestFor(kind: FrameKind, title: string, opts: NewProjectOptions): ProjectManifest {
  for (const [option, only] of Object.entries(OPTION_KINDS)) {
    if (opts[option as keyof typeof OPTION_KINDS] !== undefined && kind !== only) throw new Error(`--${option} applies to ${only} projects, not a ${kind}.`);
  }
  switch (kind) {
    case "deck":
      return { kind, title };
    case "doc":
      return { kind, title, paper: opts.paper ?? "letter" };
    case "graphic":
      return { kind, title, size: (opts.size ?? "square") as never };
    case "web": {
      const list = typeof opts.viewport === "string" ? opts.viewport.split(",").map((v) => v.trim()) : (opts.viewport ?? ["desktop"]);
      const known = Object.keys(WEB_VIEWPORTS);
      const bad = list.filter((v) => !known.includes(v));
      if (bad.length || !list.length) throw new Error(`--viewport is one of ${known.join(", ")}, or several separated by commas (got "${bad.join(", ")}").`);
      const twice = list.find((v, i) => list.indexOf(v) !== i);
      if (twice) throw new Error(`--viewport lists ${twice} twice.`);
      return { kind, title, viewport: (list.length === 1 ? list[0] : list) as never };
    }
  }
}

/** A new library: project.json plus one example component. */
function newLibrary(ws: Workspace, id: string, title: string): string[] {
  const dir = join(ws.designDir, id);
  write(join(dir, "project.json"), JSON.stringify({ kind: "library", title }, null, 2) + "\n");
  write(join(dir, DESIGN_DOC), designDocTemplate("library", title));
  const comp = join(dir, "components", "card.tsx");
  write(comp, componentTemplate("card"));
  return [relative(ws.root, join(dir, "project.json")), relative(ws.root, join(dir, DESIGN_DOC)), relative(ws.root, comp)];
}

export function componentTemplate(slug: string): string {
  const fn = pascal(slug);
  return `import { Box, Stack, Text, type SurfaceToken } from "ided";

/** Describe when to use ${fn}. Props take tokens, never raw values. */
export function ${fn}(props: { title: string; body: string; surface?: SurfaceToken }) {
  return (
    <Box surface={props.surface ?? "paper"} pad="2xl" radius="l">
      <Stack gap="m">
        <Text type="subhead">{props.title}</Text>
        <Text type="body" color="muted">
          {props.body}
        </Text>
      </Stack>
    </Box>
  );
}
`;
}

/**
 * A new project. Like `ided add`, the name becomes a kebab-case folder ("Q3 Report" → q3-report)
 * and, unless a title is given, the name as typed is the title.
 */
export function newProject(ws: Workspace, kind: FrameKind | "library", name: string, opts: NewProjectOptions = {}): string[] {
  const id = slugify(name);
  if (!id || !PROJECT_DIR_RE.test(id)) throw new Error(`"${name}" gives no usable folder name: use letters, digits and dashes, starting with a letter.`);
  if (id === "brand") throw new Error('"brand" is reserved for the brand project.');
  const dir = join(ws.designDir, id);
  if (existsSync(dir)) throw new Error(`design/${id} already exists.`);
  if (opts.title !== undefined && !opts.title.trim()) throw new Error("--title is empty.");
  const title = opts.title?.trim() ?? (id === name ? titleCase(id) : name.trim());
  if (kind === "library") {
    for (const option of Object.keys(OPTION_KINDS)) if (opts[option as keyof typeof OPTION_KINDS] !== undefined) throw new Error(`--${option} applies to ${OPTION_KINDS[option as keyof typeof OPTION_KINDS]} projects, not a library.`);
    return newLibrary(ws, id, title);
  }
  const manifest = manifestFor(kind, title, opts);
  const rel = (p: string) => relative(ws.root, p);
  write(join(dir, "project.json"), JSON.stringify(manifest, null, 2) + "\n");
  write(join(dir, DESIGN_DOC), designDocTemplate(kind, title));
  const first = join(dir, FRAME_DIR[kind], `01-${kind === "deck" ? "title" : kind === "doc" ? "cover" : kind === "web" ? "home" : "main"}.tsx`);
  write(first, frameTemplate(kind, first.split("/").pop()!.replace(/^\d+-|\.tsx$/g, ""), title, manifest.kind === "web" ? webViewports(manifest) : undefined));
  return [rel(join(dir, "project.json")), rel(join(dir, DESIGN_DOC)), rel(first)];
}

export function frameTemplate(kind: FrameKind, slug: string, heading = titleCase(slug), viewports: WebViewport[] = []): string {
  const root = FRAME_ROOT[kind];
  const fn = pascal(slug);
  const text = JSON.stringify(heading).slice(1, -1);
  const viewport = viewports.length === 1 ? viewports[0] : undefined;
  if (kind === "web" && viewports.length > 1) {
    // One screen, every viewport: values per viewport where the layout changes, Show where parts do.
    const narrow = viewports.includes("mobile");
    return `import { Row, Screen, Show, Stack, Text, Logo } from "ided";

export default function ${fn}() {
  return (
    <${root} surface="paper" gap={{ desktop: "4xl", mobile: "3xl" }}>
      <Row justify="between" align="center">
        <Logo variant={{ desktop: "horizontal"${narrow ? ', mobile: "mark"' : ""} }} size="xs" />
        <Show on={${JSON.stringify(viewports.filter((v) => v !== "mobile"))}}>
          <Row gap="xl">
            <Text type="small">Product</Text>
            <Text type="small">Pricing</Text>
            <Text type="small">About</Text>
          </Row>
        </Show>${narrow ? `
        <Show on="mobile">
          <Text type="small">Menu</Text>
        </Show>` : ""}
      </Row>
      <Stack gap={{ desktop: "l", mobile: "m" }} width={{ desktop: "2/3", tablet: "full" }}>
        <Text type={{ desktop: "display", tablet: "title", mobile: "heading" }}>${text}</Text>
        <Text type={{ desktop: "subhead", mobile: "body" }} color="muted">
          One sentence that says what this is for.
        </Text>
      </Stack>
    </${root}>
  );
}
`;
  }
  if (kind === "web" && viewport === "mobile") {
    // A phone is too narrow for a row of links: the mark and a menu, and a headline sized to fit.
    return `import { Row, Screen, Stack, Text, Logo } from "ided";

export default function ${fn}() {
  return (
    <${root} surface="paper" gap="3xl">
      <Row justify="between" align="center">
        <Logo variant="mark" size="xs" />
        <Text type="small">Menu</Text>
      </Row>
      <Stack gap="m">
        <Text type="heading">${text}</Text>
        <Text type="body" color="muted">
          One sentence that says what this is for.
        </Text>
      </Stack>
    </${root}>
  );
}
`;
  }
  if (kind === "web") {
    const tablet = viewport === "tablet";
    return `import { Row, Screen, Stack, Text, Logo } from "ided";

export default function ${fn}() {
  return (
    <${root} surface="paper" gap="4xl">
      <Row justify="between" align="center">
        <Logo variant="horizontal" size="xs" />
        <Row gap="xl">
          <Text type="small">Product</Text>
          <Text type="small">Pricing</Text>
          <Text type="small">About</Text>
        </Row>
      </Row>
      <Stack gap="l"${tablet ? "" : ' width="2/3"'}>
        <Text type="${tablet ? "title" : "display"}">${text}</Text>
        <Text type="subhead" color="muted">
          One sentence that says what this is for.
        </Text>
      </Stack>
    </${root}>
  );
}
`;
  }
  return `import { ${root}, Stack, Text } from "ided";
import { CornerMark } from "@brand/components/corner-mark";

export default function ${fn}() {
  return (
    <${root} surface="paper" justify="end">
      <CornerMark />
      <Stack gap="l">
        <Text type="title">${text}</Text>
        <Text type="subhead" color="muted">
          Replace with a one-line summary.
        </Text>
      </Stack>
    </${root}>
  );
}
`;
}

export interface AddFrameResult {
  file: string;
}

/**
 * Add the next numbered frame to a frame project, or a component to a library
 * or the brand. Never renumbers existing frames.
 */
export function addFrame(ws: Workspace, projectId: string, name: string, opts: { component?: boolean } = {}): AddFrameResult {
  const p = getProject(ws, projectId);
  if (!p.manifest) throw new Error(`"${projectId}" has an invalid project.json; run \`ided check\`.`);
  const slug = slugify(name);
  if (!slug) throw new Error("Name must contain letters or digits.");
  if (!isFrameKind(p.kind) || opts.component) {
    const abs = join(p.dir, "components", `${slug}.tsx`);
    if (existsSync(abs)) throw new Error(`${relative(ws.root, abs)} already exists.`);
    write(abs, componentTemplate(slug));
    return { file: relative(ws.root, abs) };
  }
  const kind = p.kind;
  const next = (p.frames.at(-1)?.number ?? 0) + 1;
  const width = Math.max(2, String(next).length);
  const fileName = `${String(next).padStart(width, "0")}-${slug}.tsx`;
  const abs = join(p.dir, FRAME_DIR[kind], fileName);
  write(abs, frameTemplate(kind, slug, slug === name ? undefined : name.trim(), p.manifest.kind === "web" ? webViewports(p.manifest) : undefined));
  return { file: relative(ws.root, abs) };
}

/** Declare that `projectId` imports from `library`. */
export function useLibrary(ws: Workspace, projectId: string, library: string): string {
  const p = getProject(ws, projectId);
  const lib = getProject(ws, library);
  if (lib.kind !== "library") throw new Error(`"${library}" is a ${lib.kind}; only libraries can be dependencies.`);
  if (p.kind === "brand") throw new Error("The brand cannot depend on anything; libraries depend on the brand.");
  if (p.id === lib.id) throw new Error("A project cannot depend on itself.");
  const file = join(p.dir, "project.json");
  const original = readFileSync(file, "utf8");
  const manifest = JSON.parse(original) as { dependencies?: string[] };
  const deps = new Set(manifest.dependencies ?? []);
  if (deps.has(library)) return `${projectId} already uses ${library}`;
  deps.add(library);
  manifest.dependencies = [...deps].sort();
  writeFileSync(file, JSON.stringify(manifest, null, 2) + "\n");
  const cycle = scanWorkspace(ws.root)
    .projects.flatMap((x) => x.issues)
    .find((i) => i.message.startsWith("Dependency cycle") && i.message.includes(projectId) && i.message.includes(library));
  if (cycle) {
    writeFileSync(file, original);
    throw new Error(`Not added: ${cycle.message}`);
  }
  return `${projectId} now uses ${library}: import from "@${library}/components/<name>" and "@${library}/assets/<file>"`;
}

/** Undo `useLibrary`. Returns the project files that still import from the library. */
export function unuseLibrary(ws: Workspace, projectId: string, library: string): { message: string; stillImporting: string[] } {
  const p = getProject(ws, projectId);
  const file = join(p.dir, "project.json");
  const manifest = JSON.parse(readFileSync(file, "utf8")) as { dependencies?: string[] };
  const deps = manifest.dependencies ?? [];
  if (!deps.includes(library)) return { message: `${projectId} does not use ${library}`, stillImporting: [] };
  const rest = deps.filter((d) => d !== library);
  if (rest.length) manifest.dependencies = rest;
  else delete manifest.dependencies;
  writeFileSync(file, JSON.stringify(manifest, null, 2) + "\n");
  const stillImporting = sourceFiles(p)
    .filter((f) => new RegExp(`from\\s+["']@${library}/`).test(readFileSync(f, "utf8")))
    .map((f) => relative(ws.root, f));
  return { message: `${projectId} no longer uses ${library}`, stillImporting };
}

export function describeKinds(): string {
  return (Object.keys(FRAME_DIR) as FrameKind[]).map((k) => `${k} (${FRAME_NOUN[k]}s in ${FRAME_DIR[k]}/, root <${FRAME_ROOT[k]}>)`).join(", ");
}


export function readJson<T>(file: string, fallback: T): T {
  try {
    return JSON.parse(readFileSync(file, "utf8")) as T;
  } catch {
    return fallback;
  }
}
