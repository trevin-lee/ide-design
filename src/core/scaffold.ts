/** Write only when content changed: Vite reloads the page when a tsconfig is touched. */
function writeIfChanged(file: string, content: string) {
  if (existsSync(file) && readFileSync(file, "utf8") === content) return;
  writeFileSync(file, content);
}

export function writeGenerated(root: string) {
  const gen = join(root, DESIGN_DIR, GENERATED_DIR);
  const ws = scanWorkspace(root);
  mkdirSync(gen, { recursive: true });
  const types = (p: string) => join(TYPES_DIR, p);
  const tsconfig = {
    compilerOptions: {
      target: "ES2022",
      module: "ESNext",
      moduleResolution: "bundler",
      lib: ["ES2022", "DOM"],
      jsx: "react-jsx",
      jsxImportSource: "ided",
      strict: true,
      noEmit: true,
      skipLibCheck: true,
      isolatedModules: true,
      allowImportingTsExtensions: true,
      noUnusedLocals: true,
      noUnusedParameters: true,
      noFallthroughCasesInSwitch: true,
      types: [],
      paths: {
        ided: [types("runtime/index.d.ts")],
        "ided/jsx-runtime": [types("runtime/jsx-runtime.d.ts")],
        "ided/jsx-dev-runtime": [types("runtime/jsx-dev-runtime.d.ts")],
        // One mapping for every package, so adding a project does not change this file:
        // Vite reloads every open page, exports included, when a tsconfig changes.
        "@*": ["../*"],
      },
    },
    include: ["../**/*.ts", "../**/*.tsx", "./register.d.ts", "./assets.d.ts"],
    exclude: ["./cache"],
  };
  writeIfChanged(join(gen, "tsconfig.json"), JSON.stringify(tsconfig, null, 2) + "\n");
  writeIfChanged(
    join(gen, "register.d.ts"),
    `// Generated by ided. Registers this workspace's brand so token props are typed.\nimport type brand from "../brand/brand";\ndeclare module "ided" {\n  interface Register {\n    brand: typeof brand;\n  }\n}\nexport {};\n`,
  );
  // One exact module per asset file: importing a file that does not exist is a type error.
  const assetDecls = ws.projects.flatMap((p) =>
    p.assets
      .filter((a) => !a.startsWith("fonts/"))
      .map((a) => `declare module "@${p.id}/assets/${a}" {\n  const asset: import("ided").ImageAsset;\n  export default asset;\n}`),
  );
  writeIfChanged(join(gen, "assets.d.ts"), `// Generated by ided from every package's assets/. Do not edit.\n${assetDecls.join("\n")}\n`);
  writeIfChanged(join(gen, "README.md"), "Generated by ided on every `ided run` / `ided check`. Do not edit or commit.\n");
  write(join(root, DESIGN_DIR, "tsconfig.json"), `{\n  "extends": "./.ided/tsconfig.json"\n}\n`);
}

