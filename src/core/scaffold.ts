export interface InitOptions {
  name: string;
  sample: boolean;
}

export function initWorkspace(root: string, opts: InitOptions): string[] {
  const created: string[] = [];
  const put = (rel: string, content: string) => {
    if (write(join(root, rel), content)) created.push(rel);
  };
  const existing = existsSync(join(root, DESIGN_DIR, "brand", "brand.ts"));
  put(WORKSPACE_MARKER, JSON.stringify({ version: 1 }, null, 2) + "\n");
  const gitignore = join(root, DESIGN_DIR, ".gitignore");
  if (write(gitignore, `${GENERATED_DIR}/\n`)) created.push(relative(root, gitignore));

  // An existing workspace only gets what it is missing and never the starter again: the fonts,
  // components and sample deck may have been removed on purpose.
  if (existing) {
    created.push(...migrateManifests(root));
    created.push(...addMissingDesignDocs(root));
    writeGenerated(root);
    return created;
  }

  put(`${DESIGN_DIR}/brand/project.json`, JSON.stringify({ kind: "brand", title: `${opts.name} Brand` }, null, 2) + "\n");
  put(`${DESIGN_DIR}/brand/brand.ts`, brandTemplate(opts.name));
  put(`${DESIGN_DIR}/brand/${DESIGN_DOC}`, starterBrandDesignDoc(opts.name));
  put(`${DESIGN_DIR}/brand/assets/mark.svg`, markSvg());
  put(`${DESIGN_DIR}/brand/assets/wordmark.svg`, wordmarkSvg(opts.name));
  put(`${DESIGN_DIR}/brand/components/corner-mark.tsx`, CORNER_MARK);
  put(`${DESIGN_DIR}/brand/components/footer.tsx`, FOOTER);
  const fonts = [
    ["@fontsource-variable/inter", "files/inter-latin-wght-normal.woff2", "inter.woff2", "inter-license.txt"],
    ["@fontsource-variable/jetbrains-mono", "files/jetbrains-mono-latin-wght-normal.woff2", "jetbrains-mono.woff2", "jetbrains-mono-license.txt"],
  ] as const;
  for (const [pkg, src, dest, licDest] of fonts) {
    const target = join(root, DESIGN_DIR, "brand/assets/fonts", dest);
    if (!existsSync(target)) {
      mkdirSync(dirname(target), { recursive: true });
      copyFileSync(join(dependencyDir(pkg), src), target);
      copyFileSync(join(dependencyDir(pkg), "LICENSE"), join(dirname(target), licDest));
      created.push(relative(root, target));
    }
  }
  writeGenerated(root);
  if (opts.sample) {
    const ws = scanWorkspace(root);
    if (!ws.projects.some((p) => p.id === "intro")) {
      created.push(...newProject(ws, "deck", "intro", { title: "Design as Code" }));
      const project = join(root, DESIGN_DIR, "intro");
      rmSync(join(project, "slides", "01-title.tsx"), { force: true });
      created.splice(created.indexOf(`${DESIGN_DIR}/intro/slides/01-title.tsx`), 1);
      for (const [file, body] of Object.entries(sampleSlides())) {
        writeFileSync(join(project, "slides", file), body);
        created.push(`${DESIGN_DIR}/intro/slides/${file}`);
      }
      writeFileSync(join(project, DESIGN_DOC), sampleDesignDoc());
    }
  }
  return [...new Set(created)];
}

/** project.json keys renamed since: a doc's paper size was "page" before 0.9. Key order is kept. */
export function migrateManifests(root: string): string[] {
  const changed: string[] = [];
  const designDir = join(root, DESIGN_DIR);
  for (const id of existsSync(designDir) ? readdirSync(designDir) : []) {
    const file = join(designDir, id, "project.json");
    if (!existsSync(file)) continue;
    let m: Record<string, unknown>;
    try {
      m = JSON.parse(readFileSync(file, "utf8")) as Record<string, unknown>;
    } catch {
      continue; // `ided check` reports it
    }
    if (m.kind !== "doc" || m.page === undefined || m.paper !== undefined) continue;
    const next = Object.fromEntries(Object.entries(m).map(([k, v]) => [k === "page" ? "paper" : k, v]));
    writeFileSync(file, JSON.stringify(next, null, 2) + "\n");
    changed.push(`${relative(root, file)} ("page" renamed "paper")`);
  }
  return changed;
}

/**
 * Workspaces from before design documents existed: every project without a DESIGN.md gets the
 * unwritten template for its kind. `ided check` then warns until each is written; nothing is
 * filled in on the project's behalf, least of all the starter brand's text over a real brand.
 */
export function addMissingDesignDocs(root: string): string[] {
  const added: string[] = [];
  for (const p of scanWorkspace(root).projects) {
    if (!p.manifest) continue;
    const file = join(p.dir, DESIGN_DOC);
    if (existsSync(file)) continue;
    writeFileSync(file, designDocTemplate(p.kind, p.title));
    added.push(relative(root, file));
  }
  return added;
}

